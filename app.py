def inspect_report_visual(upload_state):
    """Inspect only the uploaded report; no persistence or inferred row linkage."""
    if not upload_state:
        raise gr.Error("Primero carga un reporte.")
    from inbody_mvp.visual_debug import render_debug
    try:
        filename, data = report_from_snapshot(upload_state)
        return render_debug(filename, data, _ocr_picture)
    except (DocumentError, RuntimeError) as exc:
        # Do not render arbitrary private exception details from model runtime.
        if isinstance(exc, RuntimeError):
            raise gr.Error("El detector IA no está disponible. Revisa las dependencias opcionales.") from exc
        raise gr.Error(str(exc)) from exc
    except Exception as exc:
        raise gr.Error(f"No se pudo mostrar el diagnóstico ({type(exc).__name__}).") from exc


@spaces.GPU
def detect_report_sections(upload_state):
    if not upload_state:
        raise gr.Error("Carga primero un reporte.")
    from inbody_mvp.section_review import propose_regions
    from inbody_mvp.visual_editor import make_editor_payload
    try:
        filename, data = report_from_snapshot(upload_state)
        rows, metadata = propose_regions(filename, data)
        return (rows, metadata,
                f"Detectadas {len(rows)} regiones. Corrígelas en el único visor.",
                make_editor_payload(filename, data, rows, metadata))
    except Exception as exc:
        raise gr.Error(f"No se pudieron detectar regiones ({type(exc).__name__}).") from exc


def preview_reviewed_sections(file_path, regions_table, metadata):
    from inbody_mvp.section_review import preview_regions
    if not file_path:
        raise gr.Error("Carga un reporte.")
    try:
        path = Path(file_path)
        return preview_regions(path.name, path.read_bytes(), regions_table, metadata)
    except DocumentError as exc:
        raise gr.Error(str(exc)) from exc


def capture_section_edits(upload_state, editor_value, metadata):
    """Capture the current canvas boxes in the review table, without approving them."""
    from inbody_mvp.visual_editor import editor_rows
    try:
        _, data = report_from_snapshot(upload_state)
        rows, _ = editor_rows(editor_value, metadata, data)
        return rows, None, (
            f"Tabla actualizada: {len(rows)} secciones del editor visual. "
            "Revisa la tabla y pulsa Validar secciones corregidas."
        )
    except DocumentError as exc:
        raise gr.Error(str(exc)) from exc
    except (ValueError, TypeError, KeyError) as exc:
        raise gr.Error("No se pudieron capturar las secciones; revisa el editor.") from exc


def approve_report_sections(upload_state, editor_value, metadata):
    """Freeze the approved selection using the upload's in-session bytes."""
    from inbody_mvp.visual_editor import editor_rows
    if not upload_state:
        raise gr.Error("Carga un reporte.")
    try:
        _, data = report_from_snapshot(upload_state)
        rows, approved = editor_rows(editor_value, metadata, data)
        return {"hash": metadata["hash"], "regions": approved}, "Secciones validadas. Ya puedes extraer."
    except (DocumentError, ValueError, TypeError, KeyError, OSError) as exc:
        raise gr.Error(str(exc)) from exc


def compare_gemini_suggestions(upload_state, consent, selected_model):
    """External review of ANONYMIZED reports only; never writes to Neon."""
    try:
        filename, data = report_from_snapshot(upload_state)
        suggestions = review_with_gemini(
            filename, data, consent=consent, model=selected_model,
        )
        return suggestions, (
            f"Gemini devolvió {len(suggestions)} candidatos sin confirmar. "
            "Compáralos con el documento. No se agregan automáticamente a las medidas."
        )
    except (DocumentError, PermissionError, ValueError, RuntimeError) as exc:
        raise gr.Error(str(exc)) from exc


