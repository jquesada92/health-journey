README_PATH = Path(__file__).resolve().with_name("README.md")


def read_readme() -> str:
    if not README_PATH.is_file():
        return "# Health Journey\n\nREADME.md no está disponible."
    text = README_PATH.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    if lines and lines[0].strip() == "---":
        for index, line in enumerate(lines[1:], start=1):
            if line.strip() == "---":
                return "".join(lines[index + 1:]).lstrip()
    return text


# Keep the existing reader initialization model to preserve ZeroGPU behavior.
# SPACE_ID is set on *all* Spaces, including CPU-only machines.
# ZeroGPU patches torch.cuda.is_available() when importing spaces first.
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
reader = easyocr.Reader(["es", "en"], gpu=DEVICE, verbose=False)


def _ocr_picture(image) -> str:
    # Return bounding boxes so the extractor can associate labels with
    # their cells in dense, multi-column InBody reports.
    return reader.readtext(
        np.asarray(image.convert("RGB")), detail=1, paragraph=False,
    )


def snapshot_upload(file_path):
    """Store upload bytes in this Gradio session before temp-file cleanup."""
    if not file_path:
        return None
    path = Path(file_path)
    try:
        if not path.is_file() or path.stat().st_size > MAX_UPLOAD_BYTES:
            raise DocumentError("Archivo inexistente o mayor de 15 MB.")
        return {"filename": path.name, "data": path.read_bytes()}
    except OSError as exc:
        raise gr.Error("No se pudo recibir el archivo. Vuelve a cargarlo.") from exc


def report_from_snapshot(upload_state):
    """Read only the in-session snapshot; never rely on /tmp/gradio later."""
    if not upload_state or not isinstance(upload_state, dict):
        raise DocumentError("Carga nuevamente el reporte para continuar.")
    name, data = upload_state.get("filename"), upload_state.get("data")
    if not name or not isinstance(data, bytes) or len(data) > MAX_UPLOAD_BYTES:
        raise DocumentError("La copia temporal del reporte no está disponible. Vuelve a cargarlo.")
    return name, data


@spaces.GPU
def process_report(file_path: str | None, approved_state=None, profile: gr.OAuthProfile | None = None):
    """Validate upload first, then authorize access to the uploaded report."""
    # No document was supplied: do not require OAuth or an OCR/GPU allocation.
    if not file_path:
        raise gr.Error("Primero carga un PDF, JPG, JPEG o PNG.")
    # OCR and CSV remain independent from Neon and public dashboard.
    # Only Neon private reads/writes need an HF OAuth session.
    try:
        require_report_access(profile)
    except PermissionError as exc:
        raise gr.Error(str(exc)) from exc
    try:
        filename, data = report_from_snapshot(file_path)
        import hashlib
        if not approved_state or approved_state.get("hash") != hashlib.sha256(data).hexdigest():
            raise DocumentError("Primero valida las secciones del archivo.")
        approved = {int(k): v for k, v in approved_state["regions"].items()}
        result = extract_document(filename, data, ocr=_ocr_picture, approved_regions=approved)
    except DocumentError as exc:
        # These messages are generated by our own validation and OCR adapter,
        # not by raw exception strings from libraries handling patient data.
        raise gr.Error(str(exc)) from exc
    except OSError as exc:
        raise gr.Error("No se pudo abrir el archivo temporal.") from exc
    except Exception as exc:
        # Do not expose document contents, traceback or identifying data to a public UI.
        raise gr.Error(f"Falló la extracción ({type(exc).__name__}).") from exc
    status = (
        f"**Archivo recibido** · **Mediciones candidatas:** {len(result.medidas)} · "
        f"**Páginas:** {len(result.texto_por_pagina)} · **Estado:** pendiente de revisión."
    )
    return (
        status,
        result.id_persona or "",
        result.modelo_inbody or "",
        result.timestamp or "",
        result.edad,
        f"Origen de la edad: {result.origen_edad or 'desconocido'}",
        result.idioma_reporte,
        review_table(result),
        "\n\n--- Página siguiente ---\n\n".join(result.texto_por_pagina),
        "\n".join(f"• {item}" for item in result.advertencias) or "Sin advertencias adicionales.",
        result.model_dump(mode="json"),
    )


def download_draft(
    table, person, model, age, extracted_state,
    profile: gr.OAuthProfile | None = None,
):
    # Anonymous OCR/CSV is available even when the public dashboard is enabled.
    # Users must anonymize sensitive files before uploading to a public Space.
    if extracted_state is None:
        raise gr.Error("Primero carga y extrae un reporte InBody.")
    try:
        require_report_access(profile)
    except PermissionError as exc:
        raise gr.Error(str(exc)) from exc
    try:
        frame = table if isinstance(table, pd.DataFrame) else pd.DataFrame(table, columns=REVIEW_COLUMNS)
        content = export_draft_csv(
            frame, person, model, source_exam_timestamp(extracted_state), age
        )
    except (ValueError, TypeError) as exc:
        raise gr.Error(str(exc)) from exc
    # Gradio handles file transfer via its temporary cache, which is cleaned periodically.
    with tempfile.NamedTemporaryFile(mode="w", suffix=".csv", prefix="inbody_borrador_", delete=False, encoding="utf-8-sig", newline="") as file:
        file.write(content)
        return file.name


def verify_neon_session(profile: gr.OAuthProfile | None = None) -> str:
    """Only checks HF OAuth and allowlist, never contacts Neon or logs secrets."""
